import test from 'node:test';
import assert from 'node:assert/strict';
import { decide, validateScenario, simulatedTools } from '../src/policy.mjs';
const now=1000;
const policy = {owner:'owner-A',resource:'mcp://resource-A',scopes:['note:read','note:write','note:delete'],generation:3};
const grant = {owner:'owner-A',resource:'mcp://resource-A',scopes:[...policy.scopes],generation:3,notBefore:900,expiresAt:1100,nonce:'nonce-1'};
const action = {tool:'write-note',owner:'owner-A',resource:'mcp://resource-A',origin:'owner',grant,expected:{decision:'ALLOW'}};
const judge = p => decide(policy,now,{...action,...p,grant:{...grant,...p.grant}},new Set());
const denied = (label, overrides, reason) => test(label,()=>assert.deepEqual(judge(overrides),{decision:'DENY',reason}));

test('simulator exposes exactly three fixed fake tools',()=>assert.deepEqual(simulatedTools,['read-note','write-note','delete-note']));
test('authorized write allowed',()=>assert.deepEqual(judge({}),{decision:'ALLOW',reason:'AUTHORIZED'}));
denied('unknown tool denied', {tool:'shell'}, 'UNKNOWN_TOOL');
denied('prototype inherited name is not a tool', {tool:'toString'}, 'UNKNOWN_TOOL');
denied('constructor property is not a tool', {tool:'constructor'}, 'UNKNOWN_TOOL');
denied('untrusted instruction cannot authorize', {origin:'untrusted'}, 'UNTRUSTED_ORIGIN');
denied('cross-owner denied', {owner:'owner-B'}, 'OWNER_MISMATCH');
denied('foreign grant owner denied', {grant:{owner:'owner-B'}}, 'OWNER_MISMATCH');
denied('request audience mismatch denied', {resource:'mcp://resource-B'}, 'AUDIENCE_MISMATCH');
denied('grant audience mismatch denied', {grant:{resource:'mcp://resource-B'}}, 'AUDIENCE_MISMATCH');
denied('stale generation denied', {grant:{generation:2}}, 'STALE_GENERATION');
denied('not before denied', {grant:{notBefore:1001}}, 'NOT_YET_VALID');
denied('expired at exact boundary', {grant:{expiresAt:1000}}, 'EXPIRED_GRANT');
denied('scopes must include required permission', {grant:{scopes:['note:read']}}, 'INSUFFICIENT_SCOPE');
denied('destructive action requires approval', {tool:'delete-note'}, 'APPROVAL_REQUIRED');
test('approved delete allowed',()=>assert.equal(judge({tool:'delete-note',approved:true}).decision,'ALLOW'));
test('replayed nonce denied',()=>assert.equal(decide(policy,now,action,new Set([grant.nonce])).reason,'REPLAYED_NONCE'));
denied('precommit fault denies with no effects', {fault:'before-commit'}, 'SIMULATED_PRECOMMIT_FAILURE');
test('postcommit fault is allowed (its report becomes UNKNOWN in runner)',()=>assert.equal(judge({fault:'after-commit'}).decision,'ALLOW'));
function scenarioWith(step=action){return {version:1,id:'case-1',clock:1000,policy,actions:[step]};}
test('valid scenario accepted',()=>assert.equal(validateScenario(scenarioWith()).version,1));
test('unknown top-level fields rejected',()=>assert.throws(()=>validateScenario({...scenarioWith(),extension:true}), /INVALID_SCENARIO/));
test('unknown action fields rejected',()=>assert.throws(()=>validateScenario(scenarioWith({...action,payload:'private'})), /INVALID_ACTION/));
test('invalid grant scope types rejected',()=>assert.throws(()=>validateScenario(scenarioWith({...action,grant:{...grant,scopes:['note:write',7]}})),/INVALID_ACTION/));
test('excessively many actions rejected',()=>assert.throws(()=>validateScenario({...scenarioWith(),actions:Array(501).fill(action)}),/INVALID_ACTION_COUNT/));
test('negative clock rejected',()=>assert.throws(()=>validateScenario({...scenarioWith(),clock:-1}),/INVALID_SCENARIO/));
test('NaN is not a clock',()=>assert.throws(()=>validateScenario({...scenarioWith(),clock:NaN}),/INVALID_SCENARIO/));
test('unknown expected fields rejected',()=>assert.throws(()=>validateScenario(scenarioWith({...action,expected:{decision:'ALLOW',token:'x'}})),/INVALID_ACTION/));
test('unknown final fields rejected',()=>assert.throws(()=>validateScenario({...scenarioWith(),expectedFinal:{secret:1}}),/INVALID_EXPECTED_FINAL/));
